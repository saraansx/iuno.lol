export const profileCacheTag = (username: string) => `profile:${username.toLowerCase().trim()}`

export function revalidateProfile(username: string) {
  if (!username) return
  revalidateTag(profileCacheTag(username), { expire: 0 })
  revalidatePath(`/${username}`)
}

